test('wallet signature creates an HttpOnly session, survives refresh and logout revokes it', async ({ page }) => {
  const account = privateKeyToAccount('0x' + '3'.repeat(64))
  await page.exposeFunction('signFixtureMessage', message => account.signMessage({ message }))
  await page.addInitScript(address => {
    window.ethereum = {
      isMetaMask: true,
      async request({ method, params }) {
        if (method === 'eth_requestAccounts' || method === 'eth_accounts') return [address]
        if (method === 'eth_chainId') return '0x14a34'
        if (method === 'personal_sign') return window.signFixtureMessage(params[0])
        throw new Error('Unexpected fixture request: ' + method)
      }, on() {}, removeListener() {},
    }
  }, account.address)
  await page.goto('/')
  await page.getByRole('button', { name: 'Sign in with wallet', exact: true }).first().click()
  await page.getByRole('link', { name: 'Open dashboard', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Reputation Overview' })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('oa_token'))).toBeNull()
  const cookies = await page.context().cookies()
  expect(cookies.find((c) => c.name === 'oa_session')?.httpOnly).toBe(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Reputation Overview' })).toBeVisible()
  await page.getByTitle('Sign out').click()
  await expect(page).toHaveURL('/')
  await page.goto('/app')
  await expect(page).toHaveURL('/')
})

