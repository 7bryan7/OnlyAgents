import { test, expect } from '@playwright/test'
import { installTestSession } from '../browser-fixture.js'

test('public network shows fleet statistics; private analyses submit the chosen agents', async ({ page }) => {
  await installTestSession(page)
  await page.goto('/app/swarms')
  await expect(page.getByRole('heading', { name: 'Public peer-audit network' })).toBeVisible()
  await expect(page.getByText('Registered agents', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Content Studio|Research & Insights|Build & Ship/ })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: /topology|Swarm members|Dynamic re-ranking/ })).toHaveCount(0)
  await expect(page.getByRole('group', { name: 'Choose swarm agents' })).toHaveCount(0)
  await expect(page.locator('svg g.node')).toHaveCount(18)
  await page.screenshot({ path: '/tmp/onlyagent-public-network.png' })
  await page.getByRole('button', { name: 'My private analyses', exact: true }).click()
  const picker = page.getByRole('group', { name: 'Choose swarm agents' })
  await expect(picker).toBeVisible()
  await page.getByPlaceholder(/Evaluate our onboarding flow/).fill('Plan a release with the selected swarm')
  const analyze = page.getByRole('button', { name: 'Analyze', exact: true })
  await picker.getByRole('checkbox', { name: /Maya Chen/ }).check()
  await expect(analyze).toBeDisabled()
  await picker.getByRole('checkbox', { name: /Marcus Webb/ }).check()
  await expect(analyze).toBeDisabled()
  await picker.getByRole('checkbox', { name: /Leo Tanaka/ }).check()
  await expect(analyze).toBeEnabled()
  await expect(page.getByRole('combobox', { name: 'Automatic swarm size' })).toHaveValue('3')
  await picker.getByRole('checkbox', { name: /Daniel Okafor/ }).check()
  await picker.getByRole('checkbox', { name: /Priya Sharma/ }).check()
  await expect(picker.getByRole('checkbox', { name: /Sofia Reyes/ })).toBeDisabled()
  await picker.getByRole('checkbox', { name: /Daniel Okafor/ }).uncheck()
  await picker.getByRole('checkbox', { name: /Priya Sharma/ }).uncheck()
  const requestPromise = page.waitForRequest(request => request.url().endsWith('/api/swarms/analyze') && request.method() === 'POST')
  await analyze.click()
  expect((await requestPromise).postDataJSON()).toEqual({ task: 'Plan a release with the selected swarm', count: 3, agentIds: ['ag-101', 'ag-102', 'ag-103'] })
  await expect(page.getByText('merged report', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Use automatic selection' }).click()
  await expect(page.getByRole('combobox', { name: 'Automatic swarm size' })).toBeEnabled()
  await page.getByRole('button', { name: 'Public network', exact: true }).click()
  await expect(picker).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Public peer-audit network' })).toBeVisible()
})

test('graph draws unique valid audit relationships, highlights neighbors and remains within mobile bounds', async ({ page }) => {
  await installTestSession(page)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/api/agents', async route => {
    const response = await route.fetch()
    const body = await response.json()
    body.agents.push({ ...body.agents[0], id: 'custom-review-agent', name: 'Custom Reviewer', isCustomAgent: true, status: 'idle' })
    body.agents = body.agents.map(agent => ({ ...agent, peers: agent.id === 'ag-101' ? ['ag-102', 'ag-102', 'ag-101', 'missing-agent'] : agent.id === 'ag-102' || agent.id === 'ag-103' ? ['ag-101'] : [] }))
    await route.fulfill({ response, json: body })
  })
  await page.goto('/app/swarms')
  await expect(page.locator('line.edge')).toHaveCount(2)
  await page.getByRole('button', { name: 'My private analyses', exact: true }).click()
  await page.getByRole('checkbox', { name: /Custom Reviewer/ }).check()
  await expect(page.getByText('1/5 selected', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Public network', exact: true }).click()
  const maya = page.locator('g.node[data-agent-id="ag-101"]')
  await maya.focus()
  await page.keyboard.press('Enter')
  await expect(maya).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('g.node[data-agent-id="ag-103"]')).toHaveCSS('opacity', '1')
  await expect(page.locator('g.node[data-agent-id="ag-104"]')).toHaveCSS('opacity', '0.25')
  await expect(page.locator('line.edge[stroke="#3d6cec"]')).toHaveCount(2)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(async () => page.locator('svg g.node').evaluateAll(nodes => nodes.every(node => {
    const matrix = node.transform.baseVal.getItem(0).matrix
    const { e: x, f: y } = matrix
    const svg = node.ownerSVGElement
    return Number.isFinite(x) && Number.isFinite(y) && x >= 0 && x <= svg.getBoundingClientRect().width && y >= 0 && y <= svg.getBoundingClientRect().height
  }))).toBe(true)
  await page.getByRole('button', { name: 'Open agent profile →' }).click()
  await expect(page).toHaveURL('/app/agents/ag-101')
  await expect(page.locator('button[aria-controls="services-navigation"]')).toHaveText('Agent Marketplace')
  expect(errors).toEqual([])
})
